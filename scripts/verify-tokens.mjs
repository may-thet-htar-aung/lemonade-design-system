#!/usr/bin/env node
// Verifies a token rebuild instead of assuming it. No dependencies.
// Run after `npm run build:tokens`, from the repo root:
//   node scripts/verify-tokens.mjs
// Exit 0 when every check passes, 1 when any fails.

import { readFileSync, existsSync, readdirSync } from 'node:fs';

const TOKENS = 'tokens';
const BUILD = process.env.BUILD_DIR || 'build';
const results = [];
const check = (name, ok, detail = []) => results.push({ name, ok, detail });

const manifest = JSON.parse(readFileSync(`${TOKENS}/manifest.json`, 'utf8'));
const collections = Object.entries(manifest.collections).map(([name, c]) => {
  const modes = Object.entries(c.modes);
  return { name, defaultMode: modes[0], otherModes: modes.slice(1) };
});
const styleFiles = Object.values(manifest.styles || {}).flat();

// Every file the manifest names exists, and nothing in tokens/ is unlisted.
{
  const listed = new Set(['manifest.json', ...collections.flatMap((c) => [c.defaultMode, ...c.otherModes].flatMap(([, f]) => f)), ...styleFiles]);
  const missing = [...listed].filter((f) => !existsSync(`${TOKENS}/${f}`));
  const unlisted = readdirSync(TOKENS).filter((f) => !listed.has(f));
  check('Manifest matches tokens/', !missing.length && !unlisted.length, [...missing.map((f) => `missing: ${f}`), ...unlisted.map((f) => `not in manifest: ${f}`)]);
}

// The CSS exists and carries the generated header.
const cssPath = `${BUILD}/css/tokens.css`;
if (!existsSync(cssPath)) {
  check('build/css/tokens.css exists', false, ['run npm run build:tokens']);
  finish();
}
const css = readFileSync(cssPath, 'utf8');
check('CSS carries the generated header', css.includes('Do not edit directly, this file was auto-generated by build-tokens.js'));

const blocks = new Map();
for (const m of css.matchAll(/^(:root|\[data-[\w-]+="[\w-]+"\]) \{\n([\s\S]*?)^\}/gm)) {
  blocks.set(m[1], new Map([...m[2].matchAll(/^\s*--([\w-]+):\s*(.*);/gm)].map((x) => [x[1], x[2]])));
}
const root = blocks.get(':root') ?? new Map();

// Token names exactly as build-tokens.js derives them: flattened path, typography split per property.
function tokenNames(file) {
  const out = new Map();
  const walk = (node, prefix) => {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith('$') || !v || typeof v !== 'object') continue;
      const name = prefix ? `${prefix}-${k}` : k;
      if ('$value' in v) {
        if (v.$type === 'typography') for (const p of Object.keys(v.$value)) out.set(`${name}-${p.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`, v);
        else out.set(name, v);
      } else walk(v, name);
    }
  };
  walk(JSON.parse(readFileSync(`${TOKENS}/${file}`, 'utf8')), '');
  return out;
}

// Every default-mode and style token reached :root.
{
  const files = [...collections.flatMap((c) => c.defaultMode[1]), ...styleFiles];
  const names = new Map(files.flatMap((f) => [...tokenNames(f)]));
  const missing = [...names.keys()].filter((n) => !root.has(n));
  check(`Every source token is in :root (${names.size} source → ${root.size} :root)`, !missing.length, missing.map((n) => `--${n}`));
  // The other direction: a :root name with no source token was added by hand, or by a rule nobody wrote down.
  const extra = [...root.keys()].filter((n) => !names.has(n));
  check('Every :root name comes from a source token', !extra.length, extra.map((n) => `--${n} has no token in ${TOKENS}/`));
}

// Every non-default mode has its block, and every block belongs to a mode in the manifest.
{
  const expected = collections.flatMap((c) => c.otherModes.map(([mode]) => `[data-${c.name}="${mode}"]`));
  const missing = expected.filter((s) => !blocks.has(s));
  const stray = [...blocks.keys()].filter((s) => s !== ':root' && !expected.includes(s));
  check(`One CSS block per non-default mode (${expected.length} expected)`, !missing.length && !stray.length, [
    ...missing.map((s) => `no block for ${s}: the mode changes nothing, or the build dropped it`),
    ...stray.map((s) => `block for a mode not in the manifest: ${s}`),
  ]);
}

// Mode blocks only override names :root declares, and every var() resolves.
{
  const stray = [];
  for (const [sel, vars] of blocks) if (sel !== ':root') for (const n of vars.keys()) if (!root.has(n)) stray.push(`${sel} --${n}`);
  const dangling = [...new Set([...css.matchAll(/var\(--([\w-]+)\)/g)].map((m) => m[1]))].filter((n) => !root.has(n));
  check('Mode blocks override only :root names, and every var() resolves', !stray.length && !dangling.length, [...stray, ...dangling.map((n) => `var(--${n}) has no definition`)]);
}

// No broken values anywhere in the output.
{
  const bad = [];
  for (const dir of ['css', 'ios', 'android']) {
    if (!existsSync(`${BUILD}/${dir}`)) { bad.push(`${BUILD}/${dir} missing`); continue; }
    for (const f of readdirSync(`${BUILD}/${dir}`)) {
      const text = readFileSync(`${BUILD}/${dir}/${f}`, 'utf8');
      for (const m of text.matchAll(/\[object Object\]|\bNaN\b|\bundefined\b|CGFloat\(NaN\)/g)) bad.push(`${dir}/${f}: ${m[0]}`);
    }
  }
  check('No [object Object], NaN or undefined in build output', !bad.length, bad);
}

// Native outputs: one base file plus one per CSS mode block, per platform.
{
  const modeBlocks = [...blocks.keys()].filter((s) => s !== ':root').map((s) => s.match(/data-([\w-]+)="([\w-]+)"/).slice(1));
  const pascal = (s) => s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());
  const snake = (s) => s.replace(/-/g, '_');
  const want = ['ios/Tokens.swift', 'android/tokens.xml', ...modeBlocks.flatMap(([c, m]) => [`ios/Tokens${pascal(c)}${pascal(m)}.swift`, `android/tokens_${snake(c)}_${snake(m)}.xml`])];
  const missing = want.filter((f) => !existsSync(`${BUILD}/${f}`));
  check(`Native files present (${want.length} expected)`, !missing.length, missing);
}

finish();

function finish() {
  for (const r of results) {
    console.log(`[${r.ok ? 'PASS' : 'FAIL'}] ${r.name}`);
    for (const d of r.detail) console.log(`   - ${d}`);
  }
  const failed = results.filter((r) => !r.ok).length;
  console.log(failed ? `RESULT: FAIL (${failed} of ${results.length})` : `RESULT: PASS (${results.length} checks)`);
  process.exit(failed ? 1 : 0);
}
