#!/usr/bin/env node
// Generates the Lemonade docs site's generated pages from the component
// library repo at a pinned commit, src/data/board.json, src/data/figma.json
// and the production Storybook's index.json.
//
//   node scripts/generate.mjs --commit <sha>
//
// Every file it writes starts with a comment saying so. Never edit those files
// by hand: change this script or its sources and run it again.
// Rules: .claude/skills/astro-page/SKILL.md in the component library repo.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_SLUG = 'may-thet-htar-aung/lemonade-design-system';
const GH = `https://github.com/${REPO_SLUG}`;

const args = process.argv.slice(2);
const commitArg = args[args.indexOf('--commit') + 1];
if (!args.includes('--commit') || !commitArg) {
  console.error('usage: node scripts/generate.mjs --commit <sha>');
  process.exit(2);
}

// ---------- git ----------
const git = (...a) => execFileSync('git', a, { cwd: SITE, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const SHA = git('rev-parse', `${commitArg}^{commit}`).trim();
const SHORT = SHA.slice(0, 7);
const show = (path) => {
  try { return git('show', `${SHA}:${path}`); } catch { return null; }
};
const tree = git('ls-tree', '-r', '--name-only', SHA).split('\n').filter(Boolean);
const tags = git('tag', '-l', 'v*', '--sort=creatordate').split('\n').filter(Boolean)
  .filter((t) => { try { git('merge-base', '--is-ancestor', t, SHA); return true; } catch { return false; } });
const firstTagContaining = (c) => {
  for (const t of tags) { try { git('merge-base', '--is-ancestor', c, t); return t; } catch { /* not in t */ } }
  return null;
};

// ---------- sources ----------
const readJson = (p) => JSON.parse(readFileSync(join(SITE, p), 'utf8'));
const board = readJson('src/data/board.json');
const figma = readJson('src/data/figma.json');
const pkg = JSON.parse(show('package.json'));
const readme = show('README.md') ?? '';
const indexTs = show('src/index.ts') ?? '';
const tokensCss = show('build/css/tokens.css');
if (!tokensCss) throw new Error('build/css/tokens.css missing at ' + SHA);

const sbRow = board.components.find((c) => c.productionStorybook);
const SB = sbRow ? new URL(sbRow.productionStorybook).origin : null;
let sbIndex = { entries: {} };
let sbIndexError = null;
if (SB) {
  try {
    const res = await fetch(`${SB}/index.json`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    sbIndex = await res.json();
  } catch (e) { sbIndexError = String(e.message || e); }
} else sbIndexError = 'no Production Storybook URL on the board';
const stories = Object.values(sbIndex.entries || {});

// ---------- helpers ----------
const GEN = '{/* Generated by docs-site/scripts/generate.mjs from ' + SHORT + '. Do not edit by hand. */}';
const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/\{/g, '&#123;').replace(/\}/g, '&#125;').replace(/\r?\n/g, ' ');
const cell = (s) => esc(s).replace(/\|/g, '\\|');
const code = (s) => '`' + String(s).replace(/`/g, '') + '`';
const codeCell = (s) => code(s).replace(/\|/g, '\\|');
const yaml = (s) => JSON.stringify(String(s));
const dirOf = (name) => name.replace(/[^A-Za-z0-9]/g, '');
const slugOf = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const norm = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const caution = (title, body) => `<Aside type="caution" title=${yaml(title)}>\n${body}\n</Aside>\n`;
const write = (rel, content) => {
  const p = join(SITE, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content.replace(/\n{3,}/g, '\n\n'));
  written.push(rel);
};
const written = [];
const figmaNodeUrl = (fileUrl, node) => {
  const u = new URL(fileUrl);
  u.search = '';
  u.searchParams.set('node-id', node.replace(':', '-'));
  return u.toString();
};
const sourceLinks = (src, figmaUrl) => String(src).split(' · ').map((s) => {
  s = s.trim();
  let m;
  if ((m = s.match(/^code:(.+?):(\d+)$/))) return `[${m[1].split('/').pop()}:${m[2]}](${GH}/blob/${SHA}/${m[1]}#L${m[2]})`;
  if ((m = s.match(/^figma:(\d+:\d+)$/)) && figmaUrl) return `[Figma ${m[1]}](${figmaNodeUrl(figmaUrl, m[1])})`;
  if ((m = s.match(/^story:(.+?):(.+)$/))) return `[${m[1].split('/').pop()} · ${m[2]}](${GH}/blob/${SHA}/${m[1]})`;
  return code(s);
}).join(' · ');

// ---------- tokens ----------
const blocks = {};
for (const m of tokensCss.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
  const sel = m[1].replace(/\/\*[\s\S]*?\*\//g, '').trim();
  const vars = {};
  for (const d of m[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) vars[d[1]] = d[2].trim();
  blocks[sel] = vars;
}
const root = blocks[':root'] || {};
const MODES = Object.keys(blocks).filter((s) => s !== ':root');
const dark = blocks['[data-semantic="dark"]'] || {};
const allNames = new Set(Object.values(blocks).flatMap((b) => Object.keys(b)));
const referenced = new Set();
for (const b of Object.values(blocks)) for (const v of Object.values(b)) for (const r of v.matchAll(/var\((--[\w-]+)/g)) referenced.add(r[1]);
const isBase = (n) => referenced.has(n);
const resolve = (name, layers, depth = 0) => {
  if (depth > 20) return '?';
  let v; for (const l of layers) if (name in l) { v = l[name]; break; }
  if (v === undefined) return null;
  return v.replace(/var\((--[\w-]+)\)/g, (_, n) => resolve(n, layers, depth + 1) ?? `var(${n})`);
};
const modesChanging = (name, seen = new Set()) => {
  if (seen.has(name)) return new Set(); seen.add(name);
  const out = new Set(MODES.filter((s) => name in blocks[s]));
  const v = root[name] ?? '';
  for (const r of v.matchAll(/var\((--[\w-]+)/g)) for (const x of modesChanging(r[1], seen)) out.add(x);
  return out;
};
const modeLabel = (s) => s.replace(/^\[data-([a-z]+)="([^"]+)"\]$/, '$1=$2');
const lightOf = (n) => resolve(n, [root]);
const darkOf = (n) => resolve(n, [dark, root]);

// ---------- components ----------
const cleared = (c) => ['Completed', 'Released'].includes(c.development) && c.releaseVerdict === 'Cleared';
const comps = board.components.map((c) => ({ ...c, dir: dirOf(c.name), slug: slugOf(c.name) }));
const byDir = Object.fromEntries(comps.map((c) => [c.dir, c]));
const pages = comps.filter(cleared);
const pageSlugs = new Set(pages.map((c) => c.slug));

for (const c of comps) {
  c.tsx = show(`src/components/${c.dir}/${c.dir}.tsx`);
  c.intentRaw = show(`src/components/${c.dir}/${c.dir}.intent.json`);
  c.intent = c.intentRaw ? JSON.parse(c.intentRaw) : null;
  c.renders = c.tsx ? [...new Set([...c.tsx.matchAll(/from '\.\.\/([A-Za-z]+)\/\1'/g)].map((m) => m[1]))] : [];
  c.stories = stories.filter((s) => s.type === 'story' && s.importPath === `./src/components/${c.dir}/${c.dir}.stories.tsx`);
  c.docsEntry = Object.values(sbIndex.entries || {}).find((s) => s.type === 'docs' && s.importPath === `./src/components/${c.dir}/${c.dir}.stories.tsx`) || null;
  c.figma_ = figma.components?.[c.name] || null;
}
for (const c of comps) c.renderedBy = comps.filter((o) => o.renders.includes(c.dir)).map((o) => o.dir);

const compLink = (dir) => {
  const c = byDir[dir];
  if (!c) return code(dir);
  if (pageSlugs.has(c.slug)) return `[${c.name}](/components/${c.slug}/)`;
  return `${c.name} (Release Verdict ${c.releaseVerdict || 'none'} at this commit, so it has no page)`;
};
const storyIframe = (id) => `${SB}/iframe.html?id=${id}&viewMode=story`;
const storyPage = (id) => `${SB}/?path=/story/${id}`;
const matchRow = (row, st) => {
  const vals = row.values.map((v) => norm(v === 'true' ? 'on' : v === 'false' ? 'off' : v)).join('-');
  const alt = row.values.map(norm).join('-');
  return st.find((s) => { const tail = s.id.split('--')[1]; return tail === vals || tail.endsWith('-' + vals) || tail === alt || tail.endsWith('-' + alt); })
    || (row.values.length === 1 && row.values[0] === 'default' && st.length === 1 ? st[0] : null);
};

const versionOfComponent = (c) => {
  const first = git('log', '--reverse', '--format=%H', SHA, '--', `:(top)src/components/${c.dir}`).split('\n').filter(Boolean)[0];
  return first ? (firstTagContaining(first) || 'unreleased') : 'unreleased';
};

// Props from the .tsx: the <Name>Props object type, its doc comments and the destructured defaults.
const parseProps = (c) => {
  const src = c.tsx || '';
  const m = src.match(new RegExp(`export type ${c.dir}Props\\s*=([\\s\\S]*?)\\n\\};`));
  const props = [];
  if (m) {
    const body = m[1].slice(m[1].lastIndexOf('{') + 1);
    const re = /(\/\*\*([\s\S]*?)\*\/\s*)?\n\s*('[^']+'|[A-Za-z_][\w]*)(\?)?:\s*([^;]+);/g;
    let x;
    while ((x = re.exec('\n' + body))) {
      props.push({
        name: x[3].replace(/'/g, ''),
        optional: !!x[4],
        type: x[5].replace(/\s+/g, ' ').trim(),
        doc: (x[2] || '').split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim()).filter(Boolean).join(' '),
      });
    }
    const base = m[1].slice(0, m[1].lastIndexOf('{')).replace(/&\s*$/, '').replace(/\s+/g, ' ').trim();
    props.base = base;
  }
  const fn = src.match(new RegExp(`export function ${c.dir}\\(\\{([\\s\\S]*?)\\}\\s*:`));
  const defaults = {};
  if (fn) for (const d of fn[1].matchAll(/('[^']+'|[\w]+)(?:\s*:\s*\w+)?\s*=\s*([^,\n]+),?/g)) defaults[d[1].replace(/'/g, '')] = d[2].trim();
  return { props, defaults };
};
const parseUnions = (c) => {
  const out = [];
  for (const m of (c.tsx || '').matchAll(/export type (\w+)\s*=\s*([^;]*?\|[^;]*?);/g)) {
    if (m[1].endsWith('Props')) continue;
    out.push({ name: m[1], values: m[2].replace(/\s+/g, ' ').replace(/^\|\s*/, '').trim() });
  }
  return out;
};
const exportsOf = (c) => {
  const line = indexTs.split('\n').find((l) => l.includes(`./components/${c.dir}/${c.dir}'`));
  if (!line) return [];
  return line.replace(/^export \{|\} from.*$/g, '').split(',').map((s) => s.trim()).filter(Boolean);
};
const logFor = (dirs) => {
  const paths = dirs.map((d) => `:(top)src/components/${d}`);
  return git('log', '--no-merges', '--format=%H%x09%h%x09%ad%x09%s', '--date=short', SHA, '--', ...paths)
    .split('\n').filter(Boolean).map((l) => { const [h, s, d, subj] = l.split('\t'); return { h, s, d, subj }; });
};

// ---------- component page ----------
const notices = [];
const componentPage = (c) => {
  const f = c.figma_;
  const it = c.intent;
  const version = versionOfComponent(c);
  const figmaUrl = c.figma;
  const L = [];
  L.push('---', `title: ${yaml(c.name)}`, `description: ${yaml(`${c.name}: usage, examples, code, design and changelog, generated from ${SHORT}.`)}`, '---', '', GEN, '');
  L.push("import { Tabs, TabItem, Aside } from '@astrojs/starlight/components';", '');
  // header strip
  L.push('<div class="lds-strip">', '');
  L.push(`**Status** ${esc(c.development)} · **Release Verdict** ${esc(c.releaseVerdict)} · **Version** ${esc(version)}`, '');
  const links = [];
  if (c.productionStorybook) links.push(`[Storybook](${c.productionStorybook})`);
  if (figmaUrl && f) links.push(`[Figma node ${f.node}](${figmaNodeUrl(figmaUrl, f.node)})`);
  else if (figmaUrl) links.push(`[Figma](${figmaUrl})`);
  links.push(`[Source on GitHub at ${SHORT}](${GH}/tree/${SHA}/src/components/${c.dir})`);
  L.push(links.join(' · '), '', '</div>', '');
  L.push('<Tabs syncKey="component">');

  // Usage
  L.push('<TabItem label="Usage">', '');
  if (!it) {
    L.push(caution('No intent file', `\`src/components/${c.dir}/${c.dir}.intent.json\` does not exist at ${SHORT}.`));
    notices.push(`${c.name} Usage (no intent file)`);
  } else {
    const list = (title, arr, fmt) => {
      L.push(`### ${title}`, '');
      if (!arr || !arr.length) {
        const gap = (it.gaps || []).find((g) => g.field === title.toLowerCase().replace(/ /g, '_')) ;
        L.push(caution(`Nothing recorded for ${title.toLowerCase()}`, gap ? esc(gap.detail) : `The intent file at ${SHORT} has no entries in this field.`));
        notices.push(`${c.name} Usage: ${title.toLowerCase()} (empty in the intent file)`);
        return;
      }
      for (const e of arr) L.push(fmt(e));
      L.push('');
    };
    list('When to use', it.use_when, (e) => `- ${esc(e.text)} <small>(${sourceLinks(e.source, figmaUrl)})</small>`);
    L.push('### Where it goes', '');
    if (it.placement?.length) { for (const e of it.placement) L.push(`- ${esc(e.text)} <small>(${sourceLinks(e.source, figmaUrl)})</small>`); L.push(''); }
    else {
      const gap = (it.gaps || []).find((g) => g.field === 'placement');
      L.push(caution('No placement recorded', gap ? esc(gap.detail) : `The intent file's placement field is empty at ${SHORT}.`));
      notices.push(`${c.name} Usage: placement (empty in the intent file)`);
    }
    list('When not to use', it.dont_use_when, (e) => `- ${esc(e.text)}${e.alternative ? ` **Use instead:** ${esc(e.alternative)}.` : ' *(The source names no alternative.)*'} <small>(${sourceLinks(e.source, figmaUrl)})</small>`);
    list('Best practice', it.best_practice, (e) => `- ${esc(e.text)} <small>(${sourceLinks(e.source, figmaUrl)})</small>`);
    L.push('### What each variant is for', '');
    if (it.variant_intent?.length) {
      L.push('| Prop | Value | Intent | Source |', '|---|---|---|---|');
      for (const v of it.variant_intent) L.push(`| ${codeCell(v.prop)} | ${codeCell(v.value)} | ${v.intent ? cell(v.intent) : '*Not stated in the source; listed as a gap.*'} | ${sourceLinks(v.source, figmaUrl).replace(/\|/g, '\\|')} |`);
      L.push('');
    } else L.push(c.figma_?.type === 'COMPONENT' ? `${esc(c.name)} has no variant properties in Figma and no variant props in code.\n` : caution('No variant intent', `The intent file's variant_intent field is empty at ${SHORT}.`));
    list('Accessibility', it.a11y, (e) => `- ${esc(e.text)} <small>(${sourceLinks(e.source, figmaUrl)})</small>`);
    if (it.gaps?.length) {
      L.push('#### Gaps listed in the intent file', '');
      for (const g of it.gaps) L.push(`- **${esc(g.field)}**: ${esc(g.detail)}`);
      L.push('');
    }
  }
  L.push('### Composition', '');
  L.push(`**Renders:** ${c.renders.length ? c.renders.map(compLink).join(', ') : 'no other component.'}`, '');
  L.push(`**Rendered by:** ${c.renderedBy.length ? c.renderedBy.map(compLink).join(', ') : 'no other component.'}`, '');
  L.push('### What this version promises', '');
  const ex = exportsOf(c);
  L.push(`Exported from the package entry (\`src/index.ts\`) at ${SHORT}: ${ex.map(code).join(', ') || 'nothing'}.`, '');
  if (version === 'unreleased') {
    L.push(caution('Not in a published version yet', `No \`v*\` tag contains this component at ${SHORT}, so no published version makes a promise about it yet. The changelog lists it under Unreleased.`));
    notices.push(`${c.name} Usage: version promise (unreleased)`);
  } else L.push(`First shipped in ${code(version)}. See the [Changelog](/get-started/changelog/).`, '');
  L.push('</TabItem>');

  // Examples
  L.push('<TabItem label="Examples">', '');
  L.push('### From the README', '');
  const readmeBlocks = [...readme.matchAll(/```tsx\n([\s\S]*?)```/g)].map((m) => m[1]).filter((b) => new RegExp(`<${c.dir}[\\s/>]`).test(b));
  if (readmeBlocks.length) for (const b of readmeBlocks) L.push('```tsx', b.trimEnd(), '```', '');
  else {
    const rendered = [...new Set([...readme.matchAll(/```tsx\n([\s\S]*?)```/g)].flatMap((m) => [...m[1].matchAll(/<([A-Z][A-Za-z]*)[\s/>]/g)].map((x) => x[1])))];
    L.push(caution('No README example', `The README at ${SHORT} has no usage example that renders ${esc(c.name)}.${rendered.length ? ` Its examples render ${rendered.join(', ')}.` : ''}`));
    notices.push(`${c.name} Examples: README example (none for this component)`);
  }
  L.push('### Stories', '');
  const matrixIds = new Set((f?.matrix || []).map((r) => matchRow(r, c.stories)?.id).filter(Boolean));
  const extra = c.stories.filter((s) => !matrixIds.has(s.id));
  if (sbIndexError) {
    L.push(caution('Storybook index unavailable', `Could not read \`${SB}/index.json\`: ${esc(sbIndexError)}.`));
    notices.push(`${c.name} Examples (Storybook index unavailable)`);
  } else if (!f) {
    L.push(caution('No Figma read', `\`src/data/figma.json\` has no entry for ${esc(c.name)}, so stories cannot be told apart from variant-matrix rows.`));
    notices.push(`${c.name} Examples (no Figma read)`);
  } else if (!extra.length) {
    L.push(caution('No example stories', `Every one of the ${c.stories.length} stories in Storybook for ${esc(c.name)} is a variant-matrix row, shown on the Design tab. There is no other story to embed.`));
    notices.push(`${c.name} Examples (every story is a matrix row)`);
  } else {
    for (const s of extra) {
      L.push(`#### ${esc(s.name)}`, '', `<iframe class="lds-story" src="${storyIframe(s.id)}" title="${esc(c.name)}: ${esc(s.name)}, light" loading="lazy"></iframe>`, '');
    }
    L.push(caution('No dark rendering', 'The production Storybook has no mode switch (`.storybook/preview.ts` defines no globals or toolbar), so stories are embedded in light only.'));
    notices.push(`${c.name} Examples (no dark switch in Storybook)`);
  }
  L.push('</TabItem>');

  // Code
  L.push('<TabItem label="Code">', '');
  L.push('### Import', '', '```tsx', `import { ${c.dir} } from '${pkg.name}';`, `import '${pkg.name}/tokens.css';`, `import '${pkg.name}/styles.css';`, '```', '');
  const { props, defaults } = parseProps(c);
  let aliasM;
  L.push('### Props', '');
  if (props.length) {
    if (props.base) L.push(`Also accepts ${code(props.base)}.`, '');
    L.push('| Prop | Type | Default | Notes |', '|---|---|---|---|');
    for (const p of props) L.push(`| ${codeCell(p.name)}${p.optional ? '' : ' (required)'} | ${codeCell(p.type)} | ${defaults[p.name] ? codeCell(defaults[p.name]) : ''} | ${cell(p.doc)} |`);
    L.push('');
  } else if ((aliasM = (c.tsx || '').match(new RegExp(`export type ${c.dir}Props\\s*=\\s*([^;{]+);`)))) {
    L.push(`\`${c.dir}Props\` is ${code(aliasM[1].replace(/\s+/g, ' ').trim())}: the component has no props of its own.`, '');
  } else {
    L.push(caution('Props not found', `No \`${c.dir}Props\` object type was found in \`${c.dir}.tsx\` at ${SHORT}.`));
    notices.push(`${c.name} Code: props (not found in source)`);
  }
  const unions = parseUnions(c);
  L.push('### Union types', '');
  if (unions.length) { for (const u of unions) L.push(`- ${code(u.name)}: ${code(u.values)}`); L.push(''); }
  else L.push(`\`${c.dir}.tsx\` exports no union type at ${SHORT}.`, '');
  L.push('### Tokens it needs', '');
  const req = it?.required_tokens || [];
  if (req.length) {
    L.push('| Token | Light | Dark | Changes with |', '|---|---|---|---|');
    for (const t of req) {
      const lv = lightOf(t); const dv = darkOf(t);
      L.push(`| ${codeCell(t)} | ${lv ? codeCell(lv) : '*not defined*'} | ${dv ? codeCell(dv) : '*not defined*'} | ${[...modesChanging(t)].map(modeLabel).map(code).join(', ') || '—'} |`);
    }
    L.push('');
  } else {
    L.push(caution('No token list', `The intent file's required_tokens field is empty or missing at ${SHORT}.`));
    notices.push(`${c.name} Code: tokens (no required_tokens)`);
  }
  L.push('### Storybook props table', '');
  if (c.docsEntry) L.push(`<iframe class="lds-story lds-story--docs" src="${SB}/iframe.html?id=${c.docsEntry.id}&viewMode=docs" title="${esc(c.name)} props" loading="lazy"></iframe>`, '');
  else {
    L.push(caution('No Storybook docs page', `The production Storybook's \`index.json\` has no docs entry for ${esc(c.name)}, so there is no props table to embed.`));
    notices.push(`${c.name} Code (Storybook has no docs page)`);
  }
  L.push('</TabItem>');

  // Design
  L.push('<TabItem label="Design">', '');
  if (!f) {
    L.push(caution('No Figma read', `\`src/data/figma.json\` has no entry for ${esc(c.name)}.`));
    notices.push(`${c.name} Design (no Figma read)`);
  } else {
    const nodeUrl = figmaNodeUrl(figmaUrl, f.node);
    L.push('### Figma node', '', `<iframe class="lds-figma" src="https://www.figma.com/embed?embed_host=lemonade-docs&url=${encodeURIComponent(nodeUrl)}" title="${esc(c.name)} in Figma" loading="lazy" allowfullscreen></iframe>`, '');
    L.push(`[Open node ${f.node} in Figma](${nodeUrl})`, '');
    L.push('### Variant matrix', '');
    L.push('| Figma variant | Story |', '|---|---|');
    for (const r of f.matrix) {
      const s = matchRow(r, c.stories);
      L.push(`| ${cell(r.name)} | ${s ? `[${esc(s.name)}](${storyPage(s.id)})` : '*no matching story*'} |`);
    }
    L.push('');
    L.push('### Both themes', '');
    const first = c.stories[0];
    if (first) L.push(`<iframe class="lds-story" src="${storyIframe(first.id)}" title="${esc(c.name)}: ${esc(first.name)}, light" loading="lazy"></iframe>`, '');
    L.push(caution('No dark rendering', 'The production Storybook has no mode switch, so only light can be embedded. Dark token values are listed on the Code tab.'));
    notices.push(`${c.name} Design (no dark switch in Storybook)`);
    L.push('### Values Figma never bound', '');
    const unbound = (f.unbound || []).filter((u) => !/2A313A/i.test(u));
    if (unbound.length) { for (const u of unbound) L.push(`- ${esc(u)}`); L.push(''); }
    else L.push(`Every fill, stroke, radius, padding, gap, stroke weight, fixed size and text property read on node ${f.node} is bound to a variable.`, '');
    L.push('### Design gaps recorded', '');
    if (c.designGaps?.length) {
      for (const g of c.designGaps) L.push(`- **${esc(g.case)}**: ${esc(g.text)}`);
      L.push('');
    } else L.push('No Staging Testing row for this component records a design gap.', '');
  }
  L.push('</TabItem>');

  // Changelog
  L.push('<TabItem label="Changelog">', '');
  const dirs = [c.dir, ...c.renders];
  const log = logFor(dirs);
  L.push(`Commits touching \`src/components/${c.dir}\`${c.renders.length ? ` and the components it renders (${c.renders.map(code).join(', ')})` : ''}, newest first, up to ${SHORT}.`, '');
  L.push('| Commit | Date | Change | Version |', '|---|---|---|---|');
  for (const e of log) L.push(`| [${e.s}](${GH}/commit/${e.h}) | ${e.d} | ${cell(e.subj)} | ${firstTagContaining(e.h) || 'unreleased'} |`);
  L.push('', '</TabItem>', '</Tabs>', '');
  return L.join('\n');
};

